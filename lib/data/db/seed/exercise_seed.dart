import '../../../domain/enums/training_enums.dart';

/// The seeded exercise catalog (roadmap Phase 1, step 2).
///
/// **Generated data, hand-curated content.** Each row is a *system* exercise:
/// it stores a `nameKey` that resolves through ARB, so the catalog localizes
/// for free when a second locale ships (ADR §12.4). User-created exercises
/// store literal text in `customName` instead and are never translated.
///
/// Adding a row here means adding the matching `ex…` entry to
/// `lib/l10n/arb/app_en.arb` and a case to `exerciseDisplayName` — all three
/// are checked against each other by `test/data/exercise_seed_test.dart`, so a
/// half-added exercise fails the build rather than rendering blank in a chart
/// legend six weeks later.
///
/// `aliases` seed the plan parser's matcher (ADR §7.3); it appends to them
/// every time the user confirms a match, so the catalog gets smarter with each
/// import.
class SeedExercise {
  const SeedExercise({
    required this.nameKey,
    required this.pattern,
    required this.loadType,
    this.isUnilateral = false,
    this.primaryMuscles = const [],
    this.aliases = const [],
  });

  final String nameKey;
  final MovementPattern pattern;
  final LoadType loadType;
  final bool isUnilateral;

  /// Stable identifiers, not display text. Nothing renders these yet; when
  /// something does, they resolve through ARB like every other key.
  final List<String> primaryMuscles;

  final List<String> aliases;
}

